-- ═══════════════════════════════════════════════════════════════
--  V4 — Credencial profissional: engenheiro, arquiteto e analista
-- ═══════════════════════════════════════════════════════════════
--
--  Todo mundo entra na plataforma como cliente. Ser engenheiro e uma
--  credencial verificada por cima disso, nao um tipo de conta separado.
--
--  Poderia ter sido um valor a mais em TipoUsuario. Nao foi, por tres razoes:
--  registro profissional VENCE e pode ser suspenso, e um enum nao sabe dizer
--  "valida ate 03/2027"; uma pessoa acumula papeis (o engenheiro mora num
--  condominio e opina como morador); e TipoUsuario vira role do Spring
--  Security, entao tres valores novos multiplicariam a matriz de permissao de
--  todas as rotas do sistema.
--
--  ENGENHEIRO e ARQUITETO tem conselho com consulta publica — o numero
--  informado e conferivel na fonte, o que vale muito mais do que olhar um PDF
--  que qualquer um forja. ANALISTA nao tem conselho: e designacao interna e
--  nasce aprovada, sem documento.
--
--  O documento de prova segue a mesma politica do comprovante de residencia:
--  volume proprio fora da web, nome UUID, e apagado assim que a analise
--  termina, restando so a marca de quando foi apagado.

CREATE TABLE public.credenciais_profissionais (
    id bigint NOT NULL,
    data_analise timestamp(6) without time zone,
    data_solicitacao timestamp(6) without time zone,
    documento_arquivo character varying(255),
    documento_nome_original character varying(255),
    documento_removido_em timestamp(6) without time zone,
    motivo_recusa text,
    numero_registro character varying(255),
    profissao character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    uf_registro character varying(2),
    valido_ate date,
    analisado_por_id bigint,
    usuario_id bigint NOT NULL,
    CONSTRAINT credenciais_profissionais_profissao_check CHECK (((profissao)::text = ANY ((ARRAY['ENGENHEIRO'::character varying, 'ARQUITETO'::character varying, 'ANALISTA'::character varying])::text[]))),
    CONSTRAINT credenciais_profissionais_status_check CHECK (((status)::text = ANY ((ARRAY['PENDENTE'::character varying, 'APROVADA'::character varying, 'RECUSADA'::character varying, 'REVOGADA'::character varying])::text[])))
);
