-- ═══════════════════════════════════════════════════════════════
--  V2 — Condominios cadastrados, acesso por condominio e opiniao do morador
-- ═══════════════════════════════════════════════════════════════
--
--  Ate aqui a avaliacao IQC guardava a identidade do condominio em campos
--  soltos, e a permissao era so por papel. Esta migracao introduz:
--
--   condominios          cadastro do empreendimento (CNPJ, endereco, lat/long)
--   acessos_condominio   quem pode o que, em qual condominio. Uma tabela para
--                        solicitacao e concessao: o avaliador entra APROVADO
--                        pela mao de quem administra, o morador entra PENDENTE
--                        com o comprovante de residencia anexado
--   opinioes_morador     as respostas que formam os 10% do score final
--
--  Mais as colunas do bloco de moradores em avaliacoes_iqc. Todas nullable de
--  proposito: a tabela ja tem linhas em producao, e ADD COLUMN NOT NULL sem
--  DEFAULT falha em tabela populada.
--
--  Os nomes de constraint gerados pelo Hibernate (fk<hash>) foram preservados
--  como estao em producao. Um banco reconstruido do zero por estas migracoes
--  fica identico ao de producao, que e justamente o ponto do baseline.

CREATE TABLE public.acessos_condominio (
    id bigint NOT NULL,
    comprovante_arquivo character varying(255),
    comprovante_nome_original character varying(255),
    comprovante_removido_em timestamp(6) without time zone,
    comprovante_tamanho bigint,
    comprovante_tipo character varying(255),
    data_analise timestamp(6) without time zone,
    data_solicitacao timestamp(6) without time zone,
    morador_desde date,
    motivo_recusa text,
    papel character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    unidade character varying(255),
    vinculo character varying(255),
    analisado_por_id bigint,
    condominio_id bigint NOT NULL,
    usuario_id bigint NOT NULL,
    CONSTRAINT acessos_condominio_papel_check CHECK (((papel)::text = ANY ((ARRAY['AVALIADOR'::character varying, 'MORADOR'::character varying])::text[]))),
    CONSTRAINT acessos_condominio_status_check CHECK (((status)::text = ANY ((ARRAY['PENDENTE'::character varying, 'APROVADO'::character varying, 'RECUSADO'::character varying, 'REVOGADO'::character varying])::text[]))),
    CONSTRAINT acessos_condominio_vinculo_check CHECK (((vinculo)::text = ANY ((ARRAY['PROPRIETARIO'::character varying, 'INQUILINO'::character varying])::text[])))
);

ALTER TABLE public.acessos_condominio ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.acessos_condominio_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.condominios (
    id bigint NOT NULL,
    administradora character varying(255),
    ano_entrega integer,
    ativo boolean NOT NULL,
    bairro character varying(255),
    cep character varying(8),
    cidade character varying(255),
    cnpj character varying(14),
    complemento character varying(255),
    construtora character varying(255),
    data_atualizacao timestamp(6) without time zone,
    data_criacao timestamp(6) without time zone,
    email_contato character varying(255),
    latitude double precision,
    longitude double precision,
    nome character varying(255) NOT NULL,
    numero character varying(255),
    observacoes text,
    qtd_torres integer,
    qtd_unidades integer,
    razao_social character varying(255),
    rua character varying(255),
    telefone_contato character varying(255),
    tipo_condominio character varying(255),
    uf character varying(2),
    criado_por_id bigint,
    CONSTRAINT condominios_tipo_condominio_check CHECK (((tipo_condominio)::text = ANY ((ARRAY['HORIZONTAL'::character varying, 'VERTICAL'::character varying, 'MISTO'::character varying])::text[])))
);

ALTER TABLE public.condominios ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.condominios_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

