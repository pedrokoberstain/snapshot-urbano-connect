--  V3 — Laudo colaborativo: as tres partes do IQC
-- ═══════════════════════════════════════════════════════════════
--
--  Ate aqui a avaliacao tinha um dono so, e quem nao a criou nao conseguia
--  edita-la. Isso impedia o fluxo real do laudo: engenheiro, arquiteto e
--  analista trabalhando no mesmo condominio, cada um nas dimensoes da sua
--  especialidade.
--
--  A avaliacao passa a ser dividida em tres partes. As respostas continuam
--  num unico jsonb — o motor de calculo nao muda —, mas quem pode gravar cada
--  chave depende da dimensao a que ela pertence, e isso e filtrado no
--  servidor, nao so escondido na tela.
--
--  assinado_por_nome e registro_profissional sao COPIAS tiradas no momento da
--  assinatura, nao referencias: um laudo tem de continuar dizendo qual era o
--  CREA de quem assinou naquela data, mesmo que a pessoa mude de registro ou
--  saia da plataforma depois.
--
--  Nenhuma coluna nova em avaliacoes_iqc: as avaliacoes que ja existem
--  simplesmente ficam sem partes ate alguem abrir uma nova.

CREATE TABLE public.partes_avaliacao_iqc (
    id bigint NOT NULL,
    assinado_por_nome character varying(255),
    data_atribuicao timestamp(6) without time zone,
    data_atualizacao timestamp(6) without time zone,
    data_finalizacao timestamp(6) without time zone,
    especialidade character varying(255) NOT NULL,
    registro_profissional character varying(255),
    status character varying(255) NOT NULL,
    avaliacao_id bigint NOT NULL,
    responsavel_id bigint,
    CONSTRAINT partes_avaliacao_iqc_especialidade_check CHECK (((especialidade)::text = ANY ((ARRAY['ENGENHEIRO'::character varying, 'ARQUITETO'::character varying, 'ANALISTA'::character varying])::text[]))),
    CONSTRAINT partes_avaliacao_iqc_status_check CHECK (((status)::text = ANY ((ARRAY['AGUARDANDO'::character varying, 'EM_ANDAMENTO'::character varying, 'FINALIZADA'::character varying])::text[])))
);
